const catalog = new Map(
  translated.split("\n").map((row) => {
    const [source, english, montenegrin] = row.split("|");
    return [source, { en: english, me: montenegrin }] as const;
  }),
);

export function translateUi(
  language: Language,
  source: string,
  ...values: (string | number)[]
): string {
  const prefixEnd = source.indexOf(": ");
  const prefix = prefixEnd >= 0 ? source.slice(0, prefixEnd + 1) : "";
  const prefixTranslation =
    language === "ru" ? undefined : catalog.get(prefix)?.[language];
  const text =
    language === "ru"
      ? source
      : (catalog.get(source)?.[language] ??
        (prefixTranslation
          ? prefixTranslation + source.slice(prefixEnd + 1)
          : source));
  return values.length
    ? text.replace(/\{(\d+)\}/g, (_, index) =>
        String(values[Number(index)] ?? ""),
      )
    : text;
}
