export function seedDemoCatalog(store: Store) {
  const createdAt = now();
  store.transaction(() => {
    for (const [
      key,
      providerId,
      title,
      description,
      category,
      city,
      price,
      unit,
      image,
    ] of examples) {
      store.run(
        `INSERT INTO listings (id,providerId,title,description,category,city,price,unit,image,createdAt)
         VALUES (?,?,?,?,?,?,?,?,?,?) ON CONFLICT (id) DO NOTHING`,
        `demo-listing-${key}`,
        providerId,
        title,
        description,
        category,
        city,
        price,
        unit,
        `/images/${image}.jpg`,
        createdAt,
      );
    }
  });
}
